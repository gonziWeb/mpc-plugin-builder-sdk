"""Slow Garden: AMB-1's engine (src/amb/amb.h + amb.c, unchanged) -> src/core/amb_engine.h, one engine per instance.

AMB-1 is written for one FM-1: its state lives in file-level globals. A plugin can be loaded several times in one
process, so the same code is rearranged, without changing a statement of it, into

    part A  (namespace scope)  preprocessor lines, enums, typedefs and every `const` table, in their original order
    part B  (struct Engine)    every mutable global as a data member (initialisers kept as default member
                               initialisers) and every function as a member function, in their original order

Dropped: #include / #pragma lines, `extern` declarations and function prototypes (a member needs none).
Each instance then makes its own `amb1::Engine` (value-initialised, so members without an initialiser start at zero
as C globals do).

Re-run after changing src/amb/:   python3 tools/make_engine.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "src", "amb")
DST = os.path.join(HERE, "..", "src", "core", "amb_engine.h")


def strip_comments(text):
    """Comments replaced by spaces (newlines kept), so braces and words inside them are not counted."""
    return re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), text, flags=re.S)


def items(text):
    """Split a C file into top-level items: (kind, text). kind: 'pp', 'comment', 'blank', 'code'."""
    lines = text.split("\n")
    bare = strip_comments(text).split("\n")
    out, i, n = [], 0, len(lines)
    while i < n:
        line, b = lines[i], bare[i]
        if not line.strip():
            out.append(("blank", line))
            i += 1
        elif not b.strip():                      # only a comment on this line (maybe the start of a block)
            j = i
            while j + 1 < n and lines[j + 1].strip() and not bare[j + 1].strip():
                j += 1
            out.append(("comment", "\n".join(lines[i:j + 1])))
            i = j + 1
        elif b.lstrip().startswith("#"):
            j = i
            while lines[j].rstrip().endswith("\\"):
                j += 1
            out.append(("pp", "\n".join(lines[i:j + 1])))
            i = j + 1
        else:                                    # a declaration or a function: to the end of its braces
            depth, j = 0, i
            while True:
                s = bare[j]
                depth += s.count("{") + s.count("(") - s.count("}") - s.count(")")
                if depth == 0 and s.rstrip().endswith((";", "}")):
                    break
                j += 1
            out.append(("code", "\n".join(lines[i:j + 1])))
            i = j + 1
    return out


def classify(code):
    """'A' (namespace scope), 'B' (member) or None (dropped), and the text to emit."""
    bare = strip_comments(code).strip()
    if bare.startswith("extern "):
        return None, code
    if bare.startswith(("typedef ", "enum ")):
        return "A", code
    head = re.split(r"[{=;]", bare, maxsplit=1)[0]
    unstatic = re.sub(r"^static\s+", "", code, count=1)
    if "(" in head:                              # a function
        if "{" not in bare:
            return None, code                    # a prototype
        return "B", unstatic
    if re.match(r"(static\s+)?const\b", bare):
        return "A", code if bare.startswith("static") else "static " + code
    return "B", unstatic


def convert(name, a, b):
    text = open(os.path.join(SRC, name), encoding="utf-8").read().rstrip("\n")
    pending = []                                 # comments and blank lines go with the item that follows them
    stats = {"A": 0, "B": 0, None: 0}
    for kind, t in items(text):
        if kind in ("comment", "blank"):
            pending.append(t)
            continue
        if kind == "pp":
            if re.match(r"\s*#\s*(include|pragma)\b", t):
                pending = []
                continue
            dest = "A"
        else:
            dest, t = classify(t)
            stats[dest] += 1
        if dest is None:
            pending = []
            continue
        target = a if dest == "A" else b
        target.extend(pending)
        target.append(t)
        pending = []
    return stats


def main():
    a, b = [], []
    for name in ("amb.h", "amb.c"):
        a.append("/* ---- from %s " % name + "-" * 60 + " */")
        b.append("/* ---- from %s " % name + "-" * 60 + " */")
        st = convert(name, a, b)
        print("%s: %d at namespace scope, %d members, %d dropped" % (name, st["A"], st["B"], st[None]))
    out = [
        "/* SPDX-License-Identifier: MPL-2.0",
        " * Copyright (C) 2026 Charles Vestal",
        " *",
        " * GENERATED by tools/make_engine.py from src/amb/amb.h and src/amb/amb.c (AMB-1, unchanged): do not edit.",
        " * The same statements, rearranged: constants at namespace scope, the mutable state and the functions as",
        " * members of amb1::Engine, so that each plugin instance has its own engine. Rearrangement (C) 2026 Gonzi",
        " * Audio, MPL-2.0. Needs fastmath.h included first, and EN_HOST defined (the FM-1's memory sections off). */",
        "#ifndef SLOW_GARDEN_AMB_ENGINE_H",
        "#define SLOW_GARDEN_AMB_ENGINE_H",
        "#include <stdint.h>",
        "",
        "namespace amb1 {",
        "",
        "#define EN_HOST 1",
        "",
    ]
    out += a
    out += [
        "",
        "struct Engine {",
        "/* MIDI out: the MPC discards what a plugin sends, so the engine's notes go nowhere */",
        "void en_midi_out(uint32_t, uint32_t, uint32_t) {}",
        "",
    ]
    out += b
    out += ["};", "", "} // namespace amb1", "", "#endif", ""]
    os.makedirs(os.path.dirname(DST), exist_ok=True)
    with open(DST, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote", os.path.relpath(DST, os.path.join(HERE, "..")))


if __name__ == "__main__":
    sys.exit(main())
